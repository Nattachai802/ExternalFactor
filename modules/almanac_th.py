def translate_value(type_cn: str, value_cn: str) -> str:
    if not value_cn:
        return ""

    table = VALUE_TABLE.get(type_cn)
    if table and value_cn in table:
        return table[value_cn]

    if type_cn == "日柱" or type_cn == "月柱" or type_cn == "年柱":
        if len(value_cn) == 2:
            stem, branch = value_cn[0], value_cn[1]
            if stem in HEAVENLY_STEM and branch in EARTHLY_BRANCH:
                return f"{HEAVENLY_STEM[stem]} {EARTHLY_BRANCH[branch]}"

    if type_cn == "五行":
        parts = value_cn.split()
        nayin = NAYIN.get(parts[0], parts[0]) if parts else ""
        jianri = JIANRI.get(parts[1], parts[1]) if len(parts) > 1 else ""
        return f"{nayin} | {jianri}" if jianri else nayin

    if type_cn in ("宜", "忌"):
        words = []
        for w in value_cn.split():
            if w in YIJI:
                words.append(YIJI[w])
            else:
                _YIJI_MISSES.add(w)
                words.append(w)
        return " ".join(words)

    if type_cn in ("吉神宜趋", "凶煞宜忌"):
        table = GOOD_SPIRITS if type_cn == "吉神宜趋" else BAD_SPIRITS
        names = []
        for w in value_cn.split():
            if w in table:
                names.append(table[w].split(" — ")[0])
            else:
                _SPIRIT_MISSES.add(w)
                names.append(w)
        return " / ".join(names)

    if type_cn == "时辰":
        out = []
        for seg in value_cn.split(" | "):
            if seg in ("吉", "凶"):
                out.append("ฤกษ์ดี" if seg == "吉" else "ฤกษ์ร้าย")
            elif seg.startswith("宜:"):
                out.append("ควรทำ: " + translate_value("宜", seg[2:]))
            elif seg.startswith("忌:"):
                out.append("ห้ามทำ: " + translate_value("忌", seg[2:]))
            elif seg in GOOD_SPIRITS or seg in BAD_SPIRITS:
                table = GOOD_SPIRITS if seg in GOOD_SPIRITS else BAD_SPIRITS
                out.append("เทพประจำยาม: " + table[seg].split(" — ")[0])
            else:
                bits = seg.split()
                th = []
                for b in bits:
                    if b.startswith("冲") and b[1:] in ZODIAC:
                        th.append(f"ชง{ZODIAC[b[1:]]}")
                    elif b.startswith("煞") and b[1:] in DIRECTION:
                        th.append(f"ทิศร้าย{DIRECTION[b[1:]]}")
                    else:
                        th.append(b)
                out.append(" ".join(th))
        return " | ".join(out)

    if type_cn == "胎神":
        return _translate_taishen(value_cn)

    if type_cn == "农历":
        return _translate_lunar(value_cn)

    if type_cn == "干支":
        return _translate_ganzhi(value_cn)

    if type_cn == "彭祖百忌":
        return " | ".join(PENGZU.get(w, w) for w in value_cn.split())

    if type_cn == "日冲":
        zodiac = value_cn.strip()[-1:]   # strip กันช่องว่างท้ายค่าที่ scrape มา
        if zodiac in ZODIAC:
            return f"ชงกับปี{ZODIAC[zodiac]}"

    return value_cn


