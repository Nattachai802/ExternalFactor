def _translate_taishen(value_cn: str) -> str:
    parts = value_cn.split()
    place = parts[0] if parts else ""
    zone_raw = parts[1] if len(parts) > 1 else ""

    words, i = [], 0
    while i < len(place):
        for size in (3, 2, 1):
            chunk = place[i:i + size]
            if chunk in TAISHEN_PART:
                words.append(TAISHEN_PART[chunk])
                i += size
                break
        else:
            words.append(place[i])
            i += 1
    place_th = "และ".join(dict.fromkeys(words))

    zone_th = ""
    for prefix, th in TAISHEN_ZONE.items():
        if zone_raw.startswith(prefix):
            zone_th = f"{th}ทาง{DIRECTION.get(zone_raw[len(prefix):], zone_raw[len(prefix):])}"
            break
    return f"{place_th} — {zone_th}" if zone_th else place_th


def _translate_lunar(value_cn: str) -> str:
    # รองรับเดือนอธิกมาส "闰六月初八" — ปฏิทินจีนแทรกเดือนซ้ำทุก 2-3 ปี
    is_leap = value_cn.startswith("闰")
    val = value_cn[1:] if is_leap else value_cn

    for month_cn, month in LUNAR_MONTH.items():
        if val.startswith(month_cn):
            day = LUNAR_DAY.get(val[len(month_cn):])
            if not day:
                return value_cn
            phase = "ขึ้น" if day <= 15 else "แรม"
            leap = " (อธิกมาส)" if is_leap else ""
            return f"เดือน {month}{leap} {phase} {day if day <= 15 else day - 15} ค่ำ"
    return value_cn


def _translate_ganzhi(value_cn: str) -> str:
    m = re.findall(r"(\S\S)([年月日])（(\S)）", value_cn)
    if not m:
        return value_cn
    label = {"年": "ปี", "月": "เดือน", "日": "วัน"}
    out = []
    for pillar, unit, zodiac in m:
        stem = HEAVENLY_STEM.get(pillar[0], pillar[0]).split(" ")[0]
        branch = EARTHLY_BRANCH.get(pillar[1], pillar[1]).split(" ")[0]
        out.append(f"{label[unit]}{ZODIAC.get(zodiac, zodiac)} [{stem}-{branch}]")
    return " | ".join(out)


